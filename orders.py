# Αρχικοποίηση της μεταβλητής που θα αποθηκεύει το συνολικό κόστος ολόκληρης της παραγγελίας
total_order_cost = 0.0

print("--- Σύστημα Διαχείρισης Παραγγελιών ---")

# Χρήση βρόχου for για να επαναληφθεί η διαδικασία ακριβώς για 3 προϊόντα
for i in range(1, 4):
    print(f"\n[Καταχώριση για το {i}ο προϊόν]")
    
    # 1. Ζητάμε από τον χρήστη το όνομα του προϊόντος
    product_name = input("Δώστε όνομα προϊόντος: ")
    
    # 2. Ζητάμε την τιμή και τη μετατρέπουμε σε δεκαδικό αριθμό (float)
    price = float(input("Δώστε τιμή τεμαχίου (€): "))
    
    # 3. Ζητάμε την ποσότητα και τη μετατρέπουμε σε ακέραιο αριθμό (int)
    quantity = int(input("Δώστε ποσότητα: "))
    
    # 4. Υπολογισμός κόστους για το συγκεκριμένο προϊόν (Τιμή * Ποσότητα)
    item_cost = price * quantity
    
    # 5. Προσθήκη του κόστους του προϊόντος στο συνολικό κόστος της παραγγελίας
    total_order_cost += item_cost
    
    # Εμφάνιση υπολογισμού για το τρέχον προϊόν
    print(f"Κόστος {product_name}: {item_cost:.2f}€")

# Εμφάνιση του τελικού αθροίσματος της παραγγελίας
print("---------------------------------")
print(f"Συνολικό κόστος παραγγελίας: {total_order_cost:.2f}€")

# 6. Έλεγχος για δωρεάν μεταφορικά (αν το συνολικό κόστος είναι τουλάχιστον 100 ευρώ)
if total_order_cost >= 100:
    print("Συγχαρητήρια! Δικαιούστε Δωρεάν Μεταφορικά!")
else:
    # Υπολογισμός ποσού που λείπει για να κερδίσει τα δωρεάν μεταφορικά
    missing_amount = 100 - total_order_cost
    print(f"Δεν φτάσατε τα 100€. Χρειάζεστε ακόμα {missing_amount:.2f}€ για δωρεάν μεταφορικά.")

print("---------------------------------")